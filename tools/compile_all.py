"""Regenerate the shipped ``o6/ns`` packages from the installed compiler catalog.

The NodeSet2 -> Python compiler itself lives in the separate ``o6-ncc``
distribution (``pip install o6-ncc``); this wrapper owns no model list and no
resolver. It asks the compiler for its catalog, formats the generated source the
way this repository wants it, and places the result under ``o6/ns``.

Run it from the repository root:

    python tools/compile_all.py --keep-going
"""

from __future__ import annotations

import argparse
from pathlib import Path
from tempfile import TemporaryDirectory

import black

from o6_nodeset_compiler.catalog import (
    Specification,
    dependency_order,
    extract_catalog,
    generation_order,
)
from o6_nodeset_compiler.compiler import generate_python

_ROOT = Path(__file__).resolve().parents[1]
_OUT_DIR = _ROOT / "o6" / "ns"


def format_source(source: str, *, stub: bool = False) -> str:
    """Match this repository's NodeSet generator mode, which differs from its project defaults."""
    return black.format_str(
        source,
        mode=black.Mode(line_length=180, target_versions={black.TargetVersion.PY312}, is_pyi=stub),
    )


def write_if_changed(path: Path, content: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(content, encoding="utf-8")
    temporary.replace(path)
    return True


def namespace_registry(catalog: tuple[Specification, ...]) -> str:
    canonical = dependency_order(
        (model for model in catalog if model.canonical), candidates=catalog
    )
    rows = "".join(f"    {(model.shortname, model.uri, model.version)!r},\n" for model in canonical)
    return format_source(
        "# AUTO-GENERATED by tools/compile_all.py — DO NOT EDIT\n"
        "# Canonical namespaces shipped with o6-python; historical dependencies are excluded.\n"
        "from __future__ import annotations\n\n"
        "_GLOBAL_NAMESPACES: tuple[tuple[str, str, str], ...] = (\n" + rows + ")\n"
    )


def regenerate(out_dir: Path, *, keep_going: bool, description_cache: Path | None = None) -> int:
    with TemporaryDirectory(prefix="ncc-sdk-catalog-") as directory:
        catalog = extract_catalog(Path(directory))
        ordered = generation_order(catalog)
        registry = namespace_registry(catalog)
        expected = {model.shortname for model in ordered}
        for initializer in sorted(out_dir.glob("*/__init__.py")):
            package = initializer.parent
            if package.name in expected:
                continue
            with initializer.open(encoding="utf-8") as source:
                generated = source.readline().strip() == (
                    f'"""Generated OPC UA {package.name} namespace."""'
                )
            if generated:
                print(
                    f"Warning: obsolete generated package directory: {package} "
                    "(not in the generation catalog; review and remove manually)",
                    flush=True,
                )
        failed = False
        for index, model in enumerate(ordered, 1):
            try:
                package = generate_python(model, catalog, description_cache=description_cache)
                formatted = {
                    name: format_source(content, stub=name.endswith(".pyi"))
                    for name, content in package.items()
                }
                destination = out_dir / model.shortname
                changed = False
                for name, content in formatted.items():
                    changed |= write_if_changed(destination / name, content)
                for stale in (*destination.glob("*.py"), *destination.glob("*.pyi")):
                    if stale.name not in formatted:
                        stale.unlink()
                        changed = True
                print(
                    f"[{index}/{len(ordered)}] {model.shortname}: {'written' if changed else 'unchanged'}",
                    flush=True,
                )
            except Exception as exc:
                print(f"[{index}/{len(ordered)}] {model.shortname}: failed: {exc}", flush=True)
                failed = True
                if not keep_going:
                    break
        if not failed:
            write_if_changed(out_dir / "_generated_nodesets.py", registry)
        return int(failed)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=_OUT_DIR,
        help="namespace directory to write (default: the checkout's o6/ns)",
    )
    parser.add_argument(
        "--keep-going", action="store_true", help="attempt the remaining models after a failure"
    )
    parser.add_argument(
        "--description-cache", type=Path, help="JSON mapping of description URLs to text"
    )
    args = parser.parse_args(argv)
    return regenerate(
        args.out_dir, keep_going=args.keep_going, description_cache=args.description_cache
    )


if __name__ == "__main__":
    raise SystemExit(main())
